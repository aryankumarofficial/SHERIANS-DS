"""
Data Types in Python:
    Majorly 3:
        - numbers
            - int
            - float
            - complext
        - string
        - boolean
"""

# numbers

a = 45  # int
print(type(a))  # <class 'int'>

b = 12 / 3  # float
print(type(b))  # <class 'float'>

c = 12j  # complex
print(type(c))  # <class 'complex'>


# String

# str = "hello, Myself is Aryan"
str = 'Hello, myself is "Aryan"'  # str

print(type(str))  # <class 'str'>

# boolean

isReading = False  # bool

print(type(isReading))  # <class 'bool'>

x = 5
while x:
    print(x)
    x -= 1
