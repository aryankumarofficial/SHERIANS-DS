# Arithmetic operators
# 7 of them: +, -, *, /, //, **, %

# py follows BODMAS rule -  Brack of Division Mul Add Sub

a = 10
b = 12
print(a + b + 19 + 23 + 89)  # adds variables
print(a - b)  # substracts variables

print(12 + 12 - 24)  # BODMAS

# multiplication
print(12 * 2)

# Division
print(12 / 2)

# floor division
print(12 // 5)  # converts to int after division

# exponetial
print(5**2)  # 5^2

# mod -> remainders

print(36 % 5)

print((12 + 45) / 56)
